def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.DOTALL)
    fm = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("["):
            fm[key] = [
                v.strip().strip('"') for v in value.strip("[]").split(",") if v.strip()
            ]
        else:
            fm[key] = value.strip('"')
    fm["file"] = path.name
    return fm


feats = {}
for p in sorted(FEATURES.glob("FEAT-*.md")):
    fm = parse(p)
    feats[fm["id"]] = fm

assert sorted(RANK) == sorted(k[5:] for k in feats), "rank list does not match features"
assert len(set(RANK)) == len(RANK)


def tier(i):
    return "first" if i <= FIRST_END else "then" if i <= THEN_END else "later"


def ids(values):
    return ", ".join(v.replace("FEAT-", "") for v in values) or "-"


rows = []
for i, num in enumerate(RANK):
    f = feats[f"FEAT-{num}"]
    rows.append(
        f"| {i + 1} | [{f['id']}](features/{f['file']}) | {f['title']} | {f['epic']} | {f['phase']} "
        f"| {tier(i)} | {f['priority']} | {f['effort']} | {ids(f['dependencies'])} "
        f"| {', '.join(f['blocked_by_decisions']) or '-'} | {'yes' if f['agent_ready'] == 'true' else 'no'} "
        f"| {f['status']} |"
    )

